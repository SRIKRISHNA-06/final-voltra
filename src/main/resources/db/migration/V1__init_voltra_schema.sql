CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    phone VARCHAR(25),
    vehicle_model VARCHAR(80),
    vehicle_plate VARCHAR(30),
    payout_upi VARCHAR(80),
    base_address VARCHAR(160),
    wallet_balance NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE charger_stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    host_name VARCHAR(100) NOT NULL,
    host_phone VARCHAR(30),
    address VARCHAR(220) NOT NULL,
    city VARCHAR(80) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    category VARCHAR(30) NOT NULL,
    connector_type VARCHAR(40) NOT NULL,
    power_kw DOUBLE PRECISION NOT NULL,
    price_per_hour NUMERIC(10, 2) NOT NULL,
    price_per_kwh NUMERIC(10, 2) NOT NULL DEFAULT 18.00,
    total_bays INTEGER NOT NULL,
    online BOOLEAN NOT NULL,
    relay_active BOOLEAN NOT NULL,
    approval_status VARCHAR(30) NOT NULL,
    average_rating DOUBLE PRECISION NOT NULL,
    review_count INTEGER NOT NULL,
    booked_slots_preview VARCHAR(160),
    host_id BIGINT NOT NULL,
    CONSTRAINT fk_charger_host FOREIGN KEY (host_id) REFERENCES users(id)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charger_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    start_time TIMESTAMP NOT NULL,
    end_time TIMESTAMP NOT NULL,
    duration_hours DOUBLE PRECISION NOT NULL,
    estimated_kwh DOUBLE PRECISION NOT NULL,
    meter_start_kwh DOUBLE PRECISION,
    meter_end_kwh DOUBLE PRECISION,
    actual_kwh DOUBLE PRECISION,
    gross_amount NUMERIC(12, 2) NOT NULL,
    final_billed_amount NUMERIC(12, 2),
    platform_commission NUMERIC(12, 2) NOT NULL,
    host_net_amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,
    razorpay_order_id VARCHAR(80) UNIQUE,
    razorpay_payment_id VARCHAR(80),
    razorpay_refund_id VARCHAR(80),
    otp_hash VARCHAR(255),
    otp_expires_at TIMESTAMP,
    failed_otp_attempts INTEGER NOT NULL DEFAULT 0,
    reviewed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_booking_charger FOREIGN KEY (charger_id) REFERENCES charger_stations(id),
    CONSTRAINT fk_booking_driver FOREIGN KEY (driver_id) REFERENCES users(id)
);

CREATE TABLE ledger_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    host_id BIGINT NOT NULL,
    gateway_order_id VARCHAR(80) NOT NULL,
    gateway_payment_id VARCHAR(80),
    gateway_refund_id VARCHAR(80),
    gross_amount NUMERIC(12, 2) NOT NULL,
    platform_fee NUMERIC(12, 2) NOT NULL,
    host_net_amount NUMERIC(12, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    entry_note VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_ledger_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);

CREATE TABLE host_payouts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    host_id BIGINT NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    payout_upi VARCHAR(80) NOT NULL,
    status VARCHAR(30) NOT NULL,
    reference_code VARCHAR(60) NOT NULL UNIQUE,
    requested_at TIMESTAMP NOT NULL,
    processed_at TIMESTAMP,
    CONSTRAINT fk_payout_host FOREIGN KEY (host_id) REFERENCES users(id)
);

CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charger_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    driver_name VARCHAR(100) NOT NULL,
    vehicle_model VARCHAR(80),
    rating INTEGER NOT NULL,
    comment VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_review_charger FOREIGN KEY (charger_id) REFERENCES charger_stations(id)
);

CREATE INDEX idx_chargers_approval_city ON charger_stations(approval_status, city);
CREATE INDEX idx_bookings_charger_window ON bookings(charger_id, start_time, end_time);
CREATE INDEX idx_bookings_driver ON bookings(driver_id);
CREATE INDEX idx_ledger_host ON ledger_entries(host_id);
CREATE INDEX idx_payouts_host ON host_payouts(host_id);
